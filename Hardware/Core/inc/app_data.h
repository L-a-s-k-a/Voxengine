#ifndef APP_DATA_H
#define APP_DATA_H

#include <stdint.h>
#include <stdbool.h>

/* ============================================================
 *  ГЛОБАЛЬНЫЕ КОНСТАНТЫ СИСТЕМЫ
 * ============================================================ 
 */

/* Сколько каналов АЦП читаем за один запуск.
 * Канал 0 (PA0) — потенциометр "непрерывный режим".
 * Канал 3 (PA3) — потенциометр "энергосберегающий режим".
 * DMA кладёт два отсчёта подряд в g_app.adc_buffer[0..1]. 
 */
#define ADC_BUF_LEN       2

/* Окно усредняющего фильтра АЦП (скользящее среднее по N отсчётам).
 * Чем больше — тем стабильнее, но медленнее реакция на поворот ручки. 
 */
#define FILTER_N          10

/* Тайминги кнопки PC13 (пользовательская B1 на Nucleo).
 * DEBOUNCE   — сколько мс кнопка должна быть стабильно нажата, чтобы
 *              вообще начать считать удержание.
 * LONG_PRESS — сколько мс держать, чтобы сработало "длинное" нажатие
 *              (переключение питания). Иначе — "короткое" (смена режима). 
 */
#define BTN_DEBOUNCE_MS   20
#define BTN_LONG_PRESS_MS 2000

/* ============================================================
 *  ПЕРЕЧИСЛЕНИЯ (состояния системы)
 * ============================================================ */

/* Глобальный режим работы, выбирается коротким нажатием кнопки управления режимами(РС13) по кругу. */
typedef enum{
    STANDART,      // высокая скорость при WORK, низкая при CHILL
    CONTINUOUS,    // всегда фиксированная скорость (из потенциометра)
    ENERGY_SAVING, // всегда пониженная скорость (из потенциометра
} G_Mode;          // Global system mode

/* ============================================================
 *  СТРУКТУРЫ ДАННЫХ
 * ============================================================ 
 */

/* Всё "живое" состояние системы в одном месте.
 * volatile стоит на тех полях, которые пишутся в прерываниях
 * (SysTick / EXTI), а читаются в main — чтобы компилятор не кэшировал. 
 */
typedef struct
{
    /* --- снимок с АЦП (DMA пишет сюда, main читает) --- */
    volatile uint16_t   adc_buffer[ADC_BUF_LEN];
} AppData_t;

/* Параметры таймера ШИМ. Заполняется до вызова TIM1_Config.
 * PSC/ARR подобраны так, чтобы частота ШИМ была удобной для мотора. 
 */
typedef struct
{
    volatile uint16_t   ARR;                // период (верхний предел счёта)
    volatile uint16_t   PSC;                // предделитель
} InitConfig;

/* Единственные экземпляры — определены в app_data.c. */
extern AppData_t        g_app; 
extern InitConfig       init_config;
#endif